/**
 * OAuth2 Token 原型（僅包含最基本的 token 資訊）
 * OAuth2 Token prototype (minimal token info only)
 *
 * 來自 Google OAuth2 token 端點的原始回應中，最基本的必要欄位。
 * 完整的 token 回應應使用 IOAuth2Token。
 * Minimal required fields from a Google OAuth2 token endpoint response.
 * For the full token response, use IOAuth2Token instead.
 */
export type IOAuth2TokenProto = {
	/** 存取權杖 / Access token */
	accessToken: string;
	/** Token 類型（通常為 "Bearer"）/ Token type (usually "Bearer") */
	tokenType: string;
};

/**
 * OAuth2 Token（完整，對應 Google token 端點回應）
 * OAuth2 Token (full, maps to Google token endpoint response)
 *
 * 對應 Google OAuth2 token endpoint 回傳的 JSON 結構。
 * Maps to the JSON structure returned by the Google OAuth2 token endpoint.
 */
export type IOAuth2Token = IOAuth2TokenProto & {
	/** 有效期限（秒）/ Expiration (seconds) */
	expiresIn: number;
	/** 更新權杖 / Refresh token */
	refreshToken: string;
	/** 授權範圍 / OAuth2 scope */
	scope: string;
};

/**
 * 內部 OAuth2 Token（含到期時間戳）
 * Internal OAuth2 Token (with absolute expiry timestamp)
 *
 * 將 `expiresIn`（相對秒數）轉換為 `expiresAt`（絕對時間戳）以便快速比對。
 * 使用 `isFreshInternalOAuth2Token()` type guard 判斷是否仍有效。
 * Converts `expiresIn` (relative seconds) to `expiresAt` (absolute timestamp) for quick comparison.
 * Use `isFreshInternalOAuth2Token()` type guard to check if still valid.
 */
export type IInternalOAuth2Token = IOAuth2Token & {
	/**
	 * 到期絕對時間戳（毫秒）
	 * Absolute expiration timestamp (milliseconds)
	 *
	 * 計算方式：requestTime + (expiresIn - 60) * 1000
	 * 減 60 秒作為緩衝，避免 token 在邊界時間失效。
	 * Calculated as: requestTime + (expiresIn - 60) * 1000
	 * 60-second buffer to prevent token expiry at boundary time.
	 */
	expiresAt: number;
};

/**
 * 新鮮（有效）的內部 OAuth2 Token
 * Fresh (valid) Internal OAuth2 Token
 *
 * 使用 TypeScript Branded Type（幻影型別）區分已驗證有效與未驗證的 token。
 * 只有通過 `isFreshInternalOAuth2Token()` 檢查的 token 才能賦予此型別。
 * Uses TypeScript branded type (phantom type) to distinguish
 * verified-valid tokens from unverified ones.
 * Only tokens passing `isFreshInternalOAuth2Token()` get this type.
 */
export type IFreshInternalOAuth2Token = IBrand<IInternalOAuth2Token, 'IFreshInternalOAuth2Token'>;

/**
 * Type Guard：檢查 IInternalOAuth2Token 是否仍有效
 * Type guard: check if IInternalOAuth2Token is still fresh
 *
 * 比較 expiresAt 與當前時間戳。
 * 通過此檢查的 token 會被 TypeScript 縮窄為 IFreshInternalOAuth2Token。
 * Compares expiresAt against the current timestamp.
 * Passing this check narrows the type to IFreshInternalOAuth2Token.
 *
 * @param token - 待檢查的內部 token / Internal token to check
 * @returns token 是否仍有效 / Whether the token is still fresh
 */
const isFreshInternalOAuth2Token = (
	token: IInternalOAuth2Token,
): token is IFreshInternalOAuth2Token =>
{
	return token.expiresAt > Date.now();
};

